import type { ProviderEvent } from '../../providers/types';

/**
 * Folds the `usage_update` events of one provider stream into the context
 * occupancy the meter shows.
 *
 * One API call is one request, but one CLI turn is many internal requests, and
 * CLIs report two different things: a per-request context snapshot (Claude's
 * `message_start`, Devin's ATIF step metrics, OpenCode's ACP `usage_update`,
 * Freebuff's request log) and a cumulative turn receipt (`estimated: true`:
 * Claude's `result`, Codex `turn.completed`, Devin `final_metrics`, agy, Cursor).
 *
 * - The latest per-request snapshot wins. Taking the maximum kept a pre-compaction
 *   figure after the CLI had already compacted mid-turn.
 * - A cumulative receipt never replaces a per-request snapshot from the same
 *   stream, so a turn that made three requests reports the third request's
 *   context, not the sum of all three.
 * - Only when a stream has no per-request snapshot does the cumulative value
 *   stand in, flagged `estimated`, for the accounting layer to bound.
 * - Cache figures describe the occupancy sample they came with; an event
 *   that carries no `tokensIn` (billing-only receipts) never touches occupancy,
 *   its cache figures, or the estimated flag.
 */
export class TurnUsageFold {
  tokensIn = 0;
  tokensOut = 0;
  cachedInputTokens = 0;
  cacheWriteInputTokens = 0;
  usageKnown = false;
  estimated = false;
  private hasPerRequestSample = false;

  apply(event: ProviderEvent): void {
    if (event.type !== 'usage_update') return;
    this.usageKnown = true;
    if (typeof event.tokensIn !== 'number') {
      // Billing/output-only receipt (e.g. Anthropic message_delta output).
      if (typeof event.tokensOut === 'number' && event.estimated !== true) {
        this.tokensOut = Math.max(this.tokensOut, event.tokensOut);
      }
      return;
    }
    const occupancy = Math.max(0, event.tokensIn + (event.tokensCache ?? 0));
    const cumulative = event.estimated === true;
    if (cumulative) {
      // A per-request snapshot already describes this turn's live context.
      if (this.hasPerRequestSample) return;
      this.tokensIn = Math.max(this.tokensIn, occupancy);
      if (typeof event.tokensOut === 'number') {
        this.tokensOut = Math.max(this.tokensOut, event.tokensOut);
      }
      this.cachedInputTokens = Math.max(this.cachedInputTokens, event.tokensCacheRead ?? 0);
      this.cacheWriteInputTokens = Math.max(
        this.cacheWriteInputTokens,
        event.tokensCacheWrite ?? 0,
      );
      this.estimated = true;
      return;
    }
    // A zero placeholder (adapters that default a missing count to 0) is not a
    // context snapshot and must not erase a real one.
    if (occupancy <= 0 && this.tokensIn > 0) return;
    this.hasPerRequestSample = true;
    this.estimated = false;
    this.tokensIn = occupancy;
    // Output belongs to the request it was generated by; a later output-only
    // event (message_delta) refines it.
    this.tokensOut = Math.max(0, event.tokensOut ?? 0);
    this.cachedInputTokens = Math.max(0, event.tokensCacheRead ?? 0);
    this.cacheWriteInputTokens = Math.max(0, event.tokensCacheWrite ?? 0);
  }
}
