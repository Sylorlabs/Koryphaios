import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1800, height: 1043 } })).newPage();
page.on('pageerror', e => console.log('[pageerror]', e.message));
await page.addInitScript(() => {
  localStorage.setItem('koryphaios-onboarding-v1', JSON.stringify({ outcome: 'skipped', finishedAt: Date.now(), version: 1 }));
  localStorage.setItem('koryphaios-navigation-preferences-v1', JSON.stringify({ lastSessionId: 'qSeVO9t_Wg_6', sessionScope: 'project' }));
});
await page.goto('http://127.0.0.1:3013', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(9000);
const ctl = page.locator('[data-testid="composer-model-control"]');
console.log('ctl count:', await ctl.count());
console.log('ctl html:', (await ctl.first().innerHTML()).slice(0, 300));
await ctl.locator('button').first().click();
await page.waitForTimeout(800);
const search = page.getByLabel('Search quick models');
console.log('search count:', await search.count());
const labels = await page.locator('[aria-label]').evaluateAll(els => els.slice(0, 40).map(e => e.getAttribute('aria-label')));
console.log('aria labels:', labels);
await search.fill('mimo');
await page.waitForTimeout(800);
const names = await page.locator('button').allTextContents();
console.log(names.filter(n => /mimo|ultraspeed/i.test(n)));
await browser.close();
